#!/usr/bin/env node
// Regenerates lib/apple-root-certs.ts from the Apple root certificates in
// certs/apple/ (downloaded from https://www.apple.com/certificateauthority/).
// The certificates are embedded as base64 in a TS module so they are always
// inside the Vercel serverless bundle: no file tracing, no runtime fs reads.
// Run: node scripts/gen-apple-root-certs.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dir = join(root, 'certs/apple')
const files = readdirSync(dir).filter((f) => f.endsWith('.cer')).sort()

const entries = files
  .map((f) => `  // ${f}\n  '${readFileSync(join(dir, f)).toString('base64')}',`)
  .join('\n')

const out = `// GENERATED by scripts/gen-apple-root-certs.mjs from certs/apple/*.cer. Do not edit by hand.
// Apple root certificates (DER, base64) for offline App Store JWS verification.

export const APPLE_ROOT_CERTS_BASE64: readonly string[] = [
${entries}
]

export const APPLE_ROOT_CERT_FILES: readonly string[] = ${JSON.stringify(files)}
`
writeFileSync(join(root, 'lib/apple-root-certs.ts'), out)
console.log(`wrote lib/apple-root-certs.ts (${files.length} certificates)`)
